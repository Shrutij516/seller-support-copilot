"""Write services/api/.env and apps/web/.env.local for a local run against real AWS.

Run via `make live-env` (which reads the values from the AuthStack / KnowledgeBaseStack
outputs), or directly with explicit values. Both files are gitignored. None of these values is
a secret: the web client is public (no client secret), and ids/URLs only identify resources.
Deliberately writes NO AWS credentials: the API on the host uses your own `aws login` session
for Bedrock, and DynamoDB Local (started with -sharedDb) accepts any credentials.

Any existing file is copied to <name>.bak-<UTC timestamp> before being replaced.
"""

from __future__ import annotations

import argparse
import shutil
from datetime import UTC, datetime
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
API_ENV = REPO_ROOT / "services" / "api" / ".env"
WEB_ENV = REPO_ROOT / "apps" / "web" / ".env.local"

API_PORT = 8000  # host API; DynamoDB Local is on 8001, Postgres on 5432
WEB_ORIGIN = "http://localhost:3000"


def api_env(args: argparse.Namespace) -> str:
    issuer = args.issuer.rstrip("/")
    return "\n".join(
        [
            "# Generated by scripts/write_live_env.py (make live-env). Gitignored. No secrets.",
            "APP_ENV=local",
            "DATABASE_URL=postgresql://copilot:copilot@localhost:5432/copilot",
            "DYNAMODB_ENDPOINT_URL=http://localhost:8001",
            "AWS_REGION=us-east-1",
            f"CORS_ALLOW_ORIGINS={WEB_ORIGIN}",
            f"COGNITO_ISSUER={issuer}",
            f"COGNITO_JWKS_URL={issuer}/.well-known/jwks.json",
            f"COGNITO_APP_CLIENT_ID={args.client_id}",
            f"BEDROCK_KNOWLEDGE_BASE_ID={args.kb_id}",
            f"BEDROCK_MODEL_ID={args.model_id}",
            "",
        ]
    )


def web_env(args: argparse.Namespace) -> str:
    return "\n".join(
        [
            "# Generated by scripts/write_live_env.py (make live-env). Gitignored. No secrets.",
            f"NEXT_PUBLIC_API_BASE_URL=http://localhost:{API_PORT}",
            f"NEXT_PUBLIC_COGNITO_AUTHORITY={args.issuer.rstrip('/')}",
            f"NEXT_PUBLIC_COGNITO_CLIENT_ID={args.client_id}",
            f"NEXT_PUBLIC_COGNITO_DOMAIN={args.domain.rstrip('/')}",
            f"NEXT_PUBLIC_COGNITO_REDIRECT_URI={WEB_ORIGIN}/auth/callback",
            f"NEXT_PUBLIC_COGNITO_LOGOUT_URI={WEB_ORIGIN}",
            "NEXT_PUBLIC_COGNITO_SCOPE=openid email",
            "",
        ]
    )


def write_with_backup(path: Path, content: str) -> Path | None:
    backup = None
    if path.exists():
        if path.read_text() == content:
            return None
        backup = path.with_name(f"{path.name}.bak-{datetime.now(UTC).strftime('%Y%m%dT%H%M%SZ')}")
        shutil.copy2(path, backup)
    path.write_text(content)
    return backup


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--issuer", required=True)
    parser.add_argument("--client-id", required=True)
    parser.add_argument("--domain", required=True)
    parser.add_argument("--kb-id", required=True)
    parser.add_argument("--model-id", required=True)
    args = parser.parse_args()
    for path, content in ((API_ENV, api_env(args)), (WEB_ENV, web_env(args))):
        backup = write_with_backup(path, content)
        note = f" (previous copied to {backup.name})" if backup else ""
        print(f"wrote {path.relative_to(REPO_ROOT)}{note}")


if __name__ == "__main__":
    main()
